const assert = require('node:assert/strict');
const EngineModule = require('node:module');
const engineModule = new EngineModule('chat-engine');
engineModule._compile(require('node:fs').readFileSync('public/chat-engine.js', 'utf8'), 'chat-engine.cjs');
const { createAssistant } = engineModule.exports;
const a = createAssistant();
assert.match(a.reply('Hvað kostar þetta og er laust á morgun?').text, /ekki með staðfestan verðlista/);
assert.match(a.reply('Hvað kostar þetta og er laust á morgun?').text, /get ekki staðfest eða pantað tíma/);
assert.match(a.reply('Hvenær fæ ég myndirnar?').text, /staðfesta afhendingartíma/);
assert.match(a.reply('Hver ert þú?').text, /Ég er ekki Alex/);
assert.match(a.reply('Hver vann enska boltann?').text, /ekki með tilbúið svar/);
a.act('start');
a.reply('Ég vil haustmyndir með appelsínugulan kjól');
assert.match(a.reply('Hvað kostar það?').text, /verðlista/);
assert.match(a.act('continue').text, /Hvar sérðu þetta/);
a.act('answer:Úti');
a.reply('Í október');
const result = a.act('handoff');
assert.deepEqual(result.draft, { idea: 'Ég vil haustmyndir með appelsínugulan kjól\nStaður: Úti', when: 'Í október' });
assert.equal(result.section, undefined);
a.act('restart');
assert.equal(a.act('handoff').draft, undefined);
a.act('start');
assert.match(a.reply('Hætta').text, /Hvar eigum við að byrja/);
console.log('Chat checks passed: factual limits, unknown questions, draft flow, interruption/resumption, and reset.');
